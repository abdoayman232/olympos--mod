    public static StageMeta getStage(int stage) {
        return STAGES.get(Math.max(1, Math.min(12, stage)) - 1);
    }

    public static ItemStack createScrollBook(int stage) {
        StageMeta meta = getStage(stage);
        ItemStack book = new ItemStack(Items.WRITTEN_BOOK);
        List<RawFilteredPair<Text>> pagePairs = new ArrayList<>();
        for (String p : meta.pages()) {
            pagePairs.add(RawFilteredPair.of(Text.literal(p)));
        }
        String safeTitle = meta.bookTitle().length() > 30 ? meta.bookTitle().substring(0, 30) : meta.bookTitle();
        book.set(DataComponentTypes.WRITTEN_BOOK_CONTENT,
            new WrittenBookContentComponent(RawFilteredPair.of(safeTitle), meta.godNameAr(), 0, pagePairs, true));
        return book;
    }
